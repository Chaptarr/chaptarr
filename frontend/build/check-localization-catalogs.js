#!/usr/bin/env node
const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');
const { validateSourceEqualities } = require('./source-equality-audit.cjs');

const root = path.resolve(__dirname, '..', '..');
const core = path.join(root, 'src', 'NzbDrone.Core', 'Localization', 'Core');
const englishPath = path.join(core, 'en.json');
const registryPath = path.join(core, 'ui-locales.json');
const hashesPath = path.join(root, 'docs', 'localization', 'source-message-hashes.json');
const provenancePath = path.join(root, 'docs', 'localization', 'provenance.json');
const terminologyPath = path.join(root, 'docs', 'localization', 'terminology.json');
const reportPath = path.join(root, 'docs', 'localization', 'catalog-status.md');
const expectedLocaleTags = [
  'en',
  'ar',
  'az',
  'bg',
  'bn',
  'cs',
  'da',
  'de',
  'es',
  'fa',
  'fr',
  'he',
  'hi',
  'hu',
  'id',
  'it',
  'ja',
  'kk',
  'ko',
  'ms',
  'nb',
  'nl',
  'pl',
  'pt',
  'ru',
  'sv',
  'th',
  'tr',
  'uk',
  'uz',
  'vi',
  'zh-Hans',
  'es-419',
  'fr-CA',
  'pt-BR',
  'pt-PT',
  'zh-Hant',
];
const expectedRegionalFallbacks = {
  'es-419': 'es',
  'fr-CA': 'fr',
  'pt-BR': 'pt',
  'pt-PT': 'pt'
};
const errors = [];
const args = process.argv.slice(2);
const writeHashes = args.includes('--write-source-hashes');

function readJson(file) {
  return JSON.parse(fs.readFileSync(file, 'utf8'));
}

function sourceFingerprint(key, value) {
  return crypto.createHash('sha256').update(key + '\0' + value, 'utf8').digest('hex');
}

function placeholderTokens(value) {
  return (value.match(/\{[^{}]+\}/g) || []).sort();
}

function writeJson(file, value) {
  fs.writeFileSync(file, JSON.stringify(value, null, 2) + '\n');
}

function compareSourceHashes(english, snapshot) {
  const actual = Object.fromEntries(
    Object.keys(english).sort().map((key) => [key, sourceFingerprint(key, english[key])])
  );
  const expected = snapshot.messages || {};
  const changed = Object.keys(actual).filter((key) => expected[key] !== actual[key]);
  const removed = Object.keys(expected).filter((key) => !Object.prototype.hasOwnProperty.call(actual, key));

  if ((changed.length || removed.length) && !writeHashes) {
    errors.push(
      'Source fingerprints changed. Review the English copy, then run yarn localization:update-source-hashes. ' +
      'Changed or new IDs: ' + changed.slice(0, 20).join(', ') +
      (changed.length > 20 ? ', …' : '') +
      (removed.length ? '; removed IDs: ' + removed.slice(0, 20).join(', ') : '')
    );
  }

  return actual;
}

function buildStatusReport(english, registry, catalogs, provenance, fingerprints, equalities) {
  const lines = [
    '<!-- Generated by frontend/build/check-localization-catalogs.js. Do not edit by hand. -->',
    '',
    '# Localization catalog status',
    '',
    'Source catalog: **' + Object.keys(english).length + ' messages** in `en.json`. Each locale below resolves source IDs through its exact catalog, configured parent catalog, and English fallback.',
    '',
    'Source-equal exact values are separately classified as invariants or native equivalents by a source-fingerprinted agent audit; this classification does not claim qualified native review. Unclassified values remain unreviewed. Strings without an exact translation inherit from the configured parent locale or English. Machine drafts and reviewed entries are explicit fingerprinted provenance records. Existing exact translations without provenance are shown as unreviewed; they are not assumed to be machine-generated.',
    '',
    '| Locale | Exact catalog | Direction | Source IDs | Direct exact | Classified source-equal | Machine drafts | Unreviewed exact | Inherited | Reviewed |',
    '| --- | --- | --- | ---: | ---: | ---: | ---: | ---: | ---: | ---: |'
  ];

  for (const locale of registry.locales) {
    const exact = catalogs[locale.file] || {};
    const reviewed = provenance.reviewed[locale.tag] || {};
    const drafts = provenance.drafts[locale.tag] || {};
    const sourceCount = Object.keys(english).length;
    let machineDrafts = 0;
    let unreviewedExact = 0;
    let inherited = 0;
    let reviewedCount = 0;
    let directExact = 0;
    let classifiedEqual = 0;

    for (const key of Object.keys(english)) {
      if (locale.tag === 'en') {
        continue;
      } else {
        if (!Object.prototype.hasOwnProperty.call(exact, key)) {
          inherited++;
          continue;
        }

        directExact++;
        if (equalities.entries[locale.tag]?.[key]) {
          classifiedEqual++;
        } else if (reviewed[key] === fingerprints[key]) {
          reviewedCount++;
        } else if (drafts[key] === fingerprints[key] && exact[key] !== english[key]) {
          machineDrafts++;
        } else {
          unreviewedExact++;
        }
      }
    }

    const parentLabel = locale.fallback ? ' ← `' + locale.fallback + '.json`' : '';
    lines.push(
      '| `' + locale.tag + '` | `' + locale.file + '.json`' + parentLabel +
      ' | ' + locale.direction + ' | ' + sourceCount + ' | ' + directExact +
      ' | ' + classifiedEqual + ' | ' + machineDrafts + ' | ' + unreviewedExact + ' | ' + inherited +
      ' | ' + reviewedCount + ' |'
    );
  }

  return lines.join('\n') + '\n';
}

function main() {
  const english = readJson(englishPath);
  const registry = readJson(registryPath);
  const snapshot = readJson(hashesPath);
  const provenance = readJson(provenancePath);
  const terminology = readJson(terminologyPath);
  const equalities = readJson(path.join(root, 'docs/localization/source-equalities.json'));
  const keys = Object.keys(english);
  const idPattern = /^[a-z][A-Za-z0-9]*(?:\.[a-z][A-Za-z0-9]*)+$/;
  const legacyKeys = new Set(snapshot.legacyKeys || []);
  const localeTags = new Set();
  const ids = new Set();
  const fingerprints = compareSourceHashes(english, snapshot);
  const catalogFiles = fs.readdirSync(core)
    .filter((name) => name.endsWith('.json') && name !== 'ui-locales.json');
  const catalogs = {};

  for (const file of catalogFiles) {
    try {
      const catalog = readJson(path.join(core, file));
      if (!catalog || Array.isArray(catalog) || typeof catalog !== 'object') {
        errors.push(file + ' must contain a JSON object.');
        continue;
      }

      const stem = file.slice(0, -5);
      catalogs[stem] = catalog;

      for (const [key, value] of Object.entries(catalog)) {
        if (!Object.prototype.hasOwnProperty.call(english, key)) {
          errors.push(file + ' contains stale message ID ' + key + '.');
        }
        if (typeof value !== 'string' || value.trim() === '') {
          errors.push(file + ' has an empty or non-string value for ' + key + '.');
        }
      }
    } catch (error) {
      errors.push(file + ' is not valid JSON: ' + error.message);
    }
  }

  if (
    registry.version !== 1 ||
    !Array.isArray(registry.locales) ||
    registry.locales.length !== expectedLocaleTags.length
  ) {
    errors.push('ui-locales.json must define exactly ' + expectedLocaleTags.length + ' locale choices.');
  }

  const actualLocaleTags = (registry.locales || []).map((locale) => locale.tag).sort();
  if (JSON.stringify(actualLocaleTags) !== JSON.stringify([...expectedLocaleTags].sort())) {
    errors.push('ui-locales.json locale tags changed; review the supported locale set deliberately.');
  }

  for (const locale of registry.locales || []) {
    if (!locale.tag || !locale.name || !locale.file || !['ltr', 'rtl'].includes(locale.direction)) {
      errors.push('Locale entries need tag, native name, catalog file, and direction: ' + JSON.stringify(locale));
      continue;
    }

    if (localeTags.has(locale.tag)) errors.push('Duplicate locale tag ' + locale.tag + '.');
    if (ids.has(locale.id)) errors.push('Duplicate UI language ID ' + locale.id + '.');
    localeTags.add(locale.tag);
    ids.add(locale.id);

    if (!Object.prototype.hasOwnProperty.call(catalogs, locale.file)) {
      errors.push('Missing exact catalog ' + locale.file + '.json for ' + locale.tag + '.');
    }
    if (expectedRegionalFallbacks[locale.tag] && locale.fallback !== expectedRegionalFallbacks[locale.tag]) {
      errors.push(locale.tag + ' must explicitly inherit from ' + expectedRegionalFallbacks[locale.tag] + '.');
    }
    if (locale.fallback && !Object.prototype.hasOwnProperty.call(catalogs, locale.fallback)) {
      errors.push('Missing parent catalog ' + locale.fallback + '.json for ' + locale.tag + '.');
    }
  }

  if (terminology.version !== 1 || terminology.sourceLocale !== 'en' || !Array.isArray(terminology.terms)) {
    errors.push('terminology.json must define version 1, sourceLocale en, and a terms array.');
  }

  const terminologyIds = new Set();
  for (const term of terminology.terms || []) {
    if (!term.id || !idPattern.test(term.id) || terminologyIds.has(term.id)) {
      errors.push('Terminology IDs must be unique namespaced IDs: ' + JSON.stringify(term));
    }
    terminologyIds.add(term.id);

    if (!term.sourceId || !Object.prototype.hasOwnProperty.call(english, term.sourceId) ||
        english[term.sourceId] !== term.source) {
      errors.push('Terminology source must match an English catalog key: ' + JSON.stringify(term));
    }
    if (!term.meaning || !term.guidance) {
      errors.push('Terminology entries need meaning and translation guidance: ' + JSON.stringify(term));
    }
    if (!term.preferredTranslations || typeof term.preferredTranslations !== 'object' ||
        Array.isArray(term.preferredTranslations)) {
      errors.push('Terminology preferredTranslations must be an object: ' + JSON.stringify(term));
    } else {
      for (const [locale, value] of Object.entries(term.preferredTranslations)) {
        if (!localeTags.has(locale) || typeof value !== 'string' || value.trim() === '') {
          errors.push('Glossary translation needs a supported locale and non-empty wording: ' + JSON.stringify(term));
        }
      }
    }
  }

  if (!Array.isArray(terminology.literalPolicy) || terminology.literalPolicy.length === 0) {
    errors.push('terminology.json must preserve placeholders and protected literal values.');
  }

  for (const key of keys) {
    if (!legacyKeys.has(key) && !idPattern.test(key)) {
      errors.push('New message ID must be namespaced (for example ui.settings.save): ' + key);
    }
  }

  if (
    provenance.version !== 1 ||
    !provenance.reviewed ||
    typeof provenance.reviewed !== 'object' ||
    !provenance.drafts ||
    typeof provenance.drafts !== 'object'
  ) {
    errors.push('provenance.json must define version 1, reviewed, and drafts maps.');
  }

  const provenanceKeys = new Set();
  for (const [status, entriesByLocale] of [
    ['reviewed', provenance.reviewed || {}],
    ['machine draft', provenance.drafts || {}]
  ]) {
    for (const [locale, entries] of Object.entries(entriesByLocale)) {
      if (!localeTags.has(locale)) errors.push(status + ' provenance references unsupported locale ' + locale + '.');
      for (const [key, fingerprint] of Object.entries(entries)) {
        const recordKey = locale + '\0' + key;
        if (!Object.prototype.hasOwnProperty.call(english, key)) {
          errors.push(locale + ' ' + status + ' provenance references unknown message ID ' + key + '.');
        } else if (fingerprint !== fingerprints[key]) {
          errors.push(locale + ' ' + status + ' provenance is stale for ' + key + '; review the source before refreshing its fingerprint.');
        }
        const localeFile = (registry.locales.find((item) => item.tag === locale) || {}).file;
        const localeCatalog = localeFile ? catalogs[localeFile] || {} : {};
        if (!Object.prototype.hasOwnProperty.call(localeCatalog, key)) {
          errors.push(locale + ' ' + status + ' provenance requires an exact catalog value for ' + key + '.');
        } else if (
          Object.prototype.hasOwnProperty.call(english, key) &&
          JSON.stringify(placeholderTokens(english[key])) !== JSON.stringify(placeholderTokens(localeCatalog[key]))
        ) {
          errors.push(locale + ' ' + status + ' provenance has a placeholder mismatch for ' + key + '.');
        }
        if (status === 'machine draft' && locale !== 'en') {
          if (localeCatalog[key] === english[key]) {
            errors.push(locale + ' machine draft for ' + key + ' must differ from English.');
          }
        }
        if (provenanceKeys.has(recordKey)) {
          errors.push(locale + ' message ' + key + ' cannot have more than one provenance status.');
        }
        provenanceKeys.add(recordKey);
        if (status === 'machine draft' && locale === 'en') {
          errors.push('English source messages cannot be machine drafts.');
        }
      }
    }
  }


  errors.push(...validateSourceEqualities(equalities, english, registry.locales, catalogs));

  if (writeHashes) {
    const previousLegacyKeys = snapshot.legacyKeys || [];
    const invalidLegacy = keys.filter((key) => !previousLegacyKeys.includes(key) && !idPattern.test(key));
    if (invalidLegacy.length) {
      errors.push('Cannot refresh hashes: new IDs must be namespaced: ' + invalidLegacy.join(', '));
    } else {
      writeJson(hashesPath, {
        version: 1,
        algorithm: 'SHA-256 of UTF-8 key + NUL + English source text',
        legacyKeys: previousLegacyKeys.filter((key) => Object.prototype.hasOwnProperty.call(english, key)),
        messages: fingerprints
      });
    }
  }

  if (errors.length) {
    console.error('Localization check failed:');
    for (const error of errors) console.error(' - ' + error);
    process.exit(1);
  }

  if (writeHashes) {
    console.log('Updated source fingerprints for ' + keys.length + ' messages.');
    return;
  }

  const report = buildStatusReport(english, registry, catalogs, provenance, fingerprints, equalities);
  if (args.includes('--write-report')) {
    fs.writeFileSync(reportPath, report);
  } else if (args.includes('--report')) {
    process.stdout.write(report);
    return;
  } else {
    const checked = fs.readFileSync(reportPath, 'utf8').replace(/\r\n?/g, '\n');
    if (checked !== report) {
      console.error('Catalog status report is stale. Run yarn localization:update-status.');
      process.exit(1);
    }
  }

  console.log(
    'OK: ' + registry.locales.length + ' UI locales, ' + keys.length +
    ' source IDs, ' + catalogFiles.length + ' locale catalogs, source fingerprints and provenance are current.'
  );
}

main();

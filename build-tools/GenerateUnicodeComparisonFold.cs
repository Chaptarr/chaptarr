// Run from the repository root with .NET 10:
// dotnet run --file build-tools/GenerateUnicodeComparisonFold.cs -- --source <SMS author_name_fold_generated.go> [--check]
using System.Buffers.Binary;
using System.Globalization;
using System.Security.Cryptography;
using System.Text;
using System.Text.Json;
using System.Text.RegularExpressions;

if (args.Length is < 2 or > 3 || args[0] != "--source" || (args.Length == 3 && args[2] != "--check"))
{
    Console.Error.WriteLine("Usage: --source <author_name_fold_generated.go> [--check]");
    return 2;
}

const string expectedSourceHash = "5e71838f9bc555fdd2f9da151bdc99138d7df6b550b457cc6a75ddb65951d00e";
var source = File.ReadAllText(args[1]).Replace("\r\n", "\n");
var sourceHash = Convert.ToHexStringLower(SHA256.HashData(Encoding.UTF8.GetBytes(source)));
if (sourceHash != expectedSourceHash)
{
    Console.Error.WriteLine("Upstream data changed; review its provenance and policy before updating the pinned source fingerprint.");
    return 1;
}

var section = Regex.Match(source, @"var authorNameFoldReplacements = map\[rune\]string\{(.*?)\n\}", RegexOptions.Singleline).Groups[1].Value;
var mappings = new SortedDictionary<int, string>();
foreach (Match match in Regex.Matches(section, "0x([0-9A-F]+):\\s*(\".*\"),"))
{
    var codepoint = int.Parse(match.Groups[1].Value, NumberStyles.HexNumber, CultureInfo.InvariantCulture);
    var rune = new Rune(codepoint);
    if (Rune.IsLetter(rune) || Rune.GetUnicodeCategory(rune) is
        UnicodeCategory.NonSpacingMark or UnicodeCategory.SpacingCombiningMark or UnicodeCategory.EnclosingMark)
    {
        using var literal = JsonDocument.Parse(match.Groups[2].Value);
        mappings.Add(codepoint, literal.RootElement.GetString()!);
    }
}

var sourceSubsetHash = DataHash(mappings);
var rawMappings = new Dictionary<int, string>(mappings);
var closedMappingCount = 0;
// Follow only existing substitutions so uppercase/lowercase forms cannot change keys on a second normalization.
foreach (var codepoint in mappings.Keys.ToArray())
{
    var replacement = mappings[codepoint];
    var visited = new HashSet<string> { replacement };
    while (true)
    {
        var next = string.Concat(replacement.EnumerateRunes().Select(rune =>
            rawMappings.TryGetValue(rune.Value, out var mapped) ? mapped : rune.ToString()));
        if (next == replacement)
        {
            break;
        }

        if (!visited.Add(next))
        {
            Console.Error.WriteLine($"Upstream substitution cycle at U+{codepoint:X}; no data generated.");
            return 1;
        }

        replacement = next;
    }

    if (replacement != mappings[codepoint])
    {
        mappings[codepoint] = replacement;
        closedMappingCount++;
    }
}

var dataHash = DataHash(mappings);
var rulesHash = Regex.Match(source, @"authorNameFoldRulesSHA256\s*=\s*""([a-f0-9]+)""").Groups[1].Value;
var sourceDataHash = Regex.Match(source, @"authorNameFoldDataSHA256\s*=\s*""([a-f0-9]+)""").Groups[1].Value;
var postgresqlVersion = Regex.Match(source, @"authorNameFoldPostgreSQLVersion\s*=\s*("".*"")").Groups[1].Value;
var content = new StringBuilder();
content.AppendLine("// Generated by build-tools/GenerateUnicodeComparisonFold.cs; DO NOT EDIT.");
content.AppendLine("// Source: SMS PostgreSQL lower(unaccent(chr)) data; only letter and combining-mark inputs are included.");
content.AppendLine("// License notices: build-tools/unicode-comparison-fold-LICENSE.txt.");
content.AppendLine("using System.Collections.Frozen;");
content.AppendLine("using System.Collections.Generic;");
content.AppendLine();
content.AppendLine("namespace NzbDrone.Core.Utilities");
content.AppendLine("{");
content.AppendLine("    internal static class UnicodeComparisonFoldData");
content.AppendLine("    {");
content.AppendLine($"        internal const string PostgreSQLVersion = {postgresqlVersion};");
content.AppendLine($"        internal const string SourceSHA256 = \"{sourceHash}\";");
content.AppendLine($"        internal const string SourceDataSHA256 = \"{sourceDataHash}\";");
content.AppendLine($"        internal const string SourceSubsetSHA256 = \"{sourceSubsetHash}\";");
content.AppendLine($"        internal const string RulesSHA256 = \"{rulesHash}\";");
content.AppendLine($"        internal const string DataSHA256 = \"{dataHash}\";");
content.AppendLine($"        internal const int MappingCount = {mappings.Count};");
content.AppendLine($"        internal const int ClosedMappingCount = {closedMappingCount};");
content.AppendLine();
content.AppendLine("        internal static readonly FrozenDictionary<int, string> Replacements = new Dictionary<int, string>");
content.AppendLine("        {");
foreach (var (codepoint, replacement) in mappings)
{
    content.AppendLine($"            [0x{codepoint:X4}] = \"{JsonEncodedText.Encode(replacement)}\",");
}

content.AppendLine("        }.ToFrozenDictionary();");
content.AppendLine("    }");
content.AppendLine("}");

var javascript = new StringBuilder();
javascript.AppendLine("// Generated by build-tools/GenerateUnicodeComparisonFold.cs; DO NOT EDIT.");
javascript.AppendLine("// Same letter/mark mapping as UnicodeComparisonFoldData.cs. See build-tools/unicode-comparison-fold-LICENSE.txt.");
javascript.AppendLine($"export const sourceSHA256 = '{sourceHash}';");
javascript.AppendLine($"export const dataSHA256 = '{dataHash}';");
javascript.AppendLine("export default {");
foreach (var (codepoint, replacement) in mappings)
{
    javascript.AppendLine($"  0x{codepoint:X4}: \"{JsonEncodedText.Encode(replacement)}\",");
}
javascript.AppendLine("};");

var outputs = new[]
{
    (Path.Combine("src", "NzbDrone.Core", "Utilities", "UnicodeComparisonFoldData.cs"), content.ToString()),
    (Path.Combine("frontend", "src", "Utilities", "String", "unicodeComparisonFoldData.js"), javascript.ToString())
};
foreach (var (target, text) in outputs)
{
    var generated = text.Replace("\r\n", "\n");
    if (args.Length == 3)
    {
        if (!File.Exists(target) || File.ReadAllText(target).Replace("\r\n", "\n") != generated)
        {
            Console.Error.WriteLine($"Generated Unicode comparison data is out of date: {target}");
            return 1;
        }
    }
    else
    {
        File.WriteAllText(target, generated);
    }
}

Console.WriteLine($"Verified {mappings.Count} letter/mark mappings, {closedMappingCount} closed substitutions; data SHA256 {dataHash}.");
return 0;

static string DataHash(IEnumerable<KeyValuePair<int, string>> mappings)
{
    using var digest = IncrementalHash.CreateHash(HashAlgorithmName.SHA256);
    var codepointBytes = new byte[4];
    foreach (var (codepoint, replacement) in mappings)
    {
        BinaryPrimitives.WriteInt32BigEndian(codepointBytes, codepoint);
        digest.AppendData(codepointBytes);
        digest.AppendData(Encoding.UTF8.GetBytes(replacement));
        digest.AppendData(new byte[] { 0 });
    }

    return Convert.ToHexStringLower(digest.GetHashAndReset());
}

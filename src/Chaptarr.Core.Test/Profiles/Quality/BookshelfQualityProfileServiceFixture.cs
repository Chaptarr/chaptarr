            _subject.Delete(900001);
            _subject.Delete(NativeIds(first.LegacyId).Last());
            Assert.That(Snapshot(), Is.EqualTo(before));
        }

        private BookshelfQualityProfileService NewService() => new(_database, _repository, _profiles,
            new BookshelfLegacyIdentityMapService(_database), _formatService);

        private static QualityProfile Generic(string name) => new()
        {
            Name = name, Cutoff = CoreQuality.M4B.Id,
            Items = CoreQuality.All.Select(quality => new QualityProfileQualityItem { Quality = quality, Allowed = true }).ToList(),
            FormatItems = new List<ProfileFormatItem>()
        };

        private List<int> NativeIds(int legacyId)
        {
            using var connection = Open();
            return connection.Query<int>("SELECT \"TargetId\" FROM \"BookshelfLegacyIdentityMap\" WHERE \"SourceId\"=@LegacyId ORDER BY \"MediaType\"", new { LegacyId = legacyId }).ToList();
        }

        private string Snapshot()
        {
            using var connection = Open();
            // PostgreSQL sequences are deliberately nontransactional; rollback still retains
            // all logical rows and legacy identity allocation. SQLite sequence state rolls back.
            var tables = Backend == DatabaseType.PostgreSQL
                ? new[] { "QualityProfiles", "BookshelfLegacyIdentityMap", "Config" }
                : new[] { "QualityProfiles", "BookshelfLegacyIdentityMap", "Config", "sqlite_sequence" };
            return JsonSerializer.Serialize(tables.ToDictionary(table => table,
                table => connection.Query("SELECT * FROM \"" + table + "\" ORDER BY 1").Select(row => (IDictionary<string, object>)row).ToList()));
        }

        private IDbConnection Open()
        {
            IDbConnection connection = Backend == DatabaseType.PostgreSQL
                ? new NpgsqlConnection(_postgresConnection)
                : new SqliteConnection(new SqliteConnectionStringBuilder { DataSource = _path, Pooling = false }.ConnectionString);
            connection.Open();
            return connection;
        }

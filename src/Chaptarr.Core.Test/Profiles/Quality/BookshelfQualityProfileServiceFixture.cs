        [Test]
        public void generic_create_update_restart_and_delete_keep_one_wire_identity_and_two_native_profiles()
        {
            var first = _subject.Create(Generic("First"));
            var second = _subject.Create(Generic("Second"));
            Assert.That(new[] { first.LegacyId, second.LegacyId }, Is.EqualTo(new[] { 1, 2 }));
            Assert.That(second.Profile.Id, Is.EqualTo(3));
            Assert.That(_subject.All().Select(profile => profile.LegacyId), Is.EqualTo(new[] { 1, 2 }));
            var ids = NativeIds(second.LegacyId);

            var changed = Generic("Changed");
            changed.Cutoff = CoreQuality.EPUB.Id;
            changed.UpgradeAllowed = true;
            _subject.Update(second.LegacyId, changed);
            Assert.That(NativeIds(second.LegacyId), Is.EqualTo(ids));
            Assert.That(_repository.Get(ids).All(profile => profile.Name == "Changed" && profile.Cutoff == CoreQuality.EPUB.Id && profile.UpgradeAllowed), Is.True);
            _subject = NewService();
            Assert.That(_subject.Get(2).Profile.Id, Is.EqualTo(3));
            _subject.Delete(2);
            Assert.That(_repository.All().Count(), Is.EqualTo(2));
            Assert.That(_subject.All().Select(profile => profile.LegacyId), Is.EqualTo(new[] { 1 }));
            Assert.Throws<ModelNotFoundException>(() => _subject.Get(2));
            Assert.That(_subject.Create(Generic("After deletion")).LegacyId, Is.EqualTo(3));
        }

        [Test]
        public void legacy_updates_preserve_native_conversion_preferences_and_format_specific_scores()
        {
            _formats.AddRange(new[]
            {
                new CustomFormat { Id = 11, Name = "Shared" },
                new CustomFormat { Id = 22, Name = "Audio", AppliesTo = CustomFormatMediaType.Audiobook },
                new CustomFormat { Id = 33, Name = "Ebook", AppliesTo = CustomFormatMediaType.Ebook }
            });
            var source = Generic("Shared profile");
            source.FormatItems.Add(new ProfileFormatItem { Format = _formats[0], Score = 7 });
            source.FormatItems.Add(new ProfileFormatItem { Format = _formats[1], Score = 999 });
            var created = _subject.Create(source);
            var ids = NativeIds(created.LegacyId);
            foreach (var profile in _repository.Get(ids))
            {
                profile.ConvertToQualityId = profile.ProfileType == ProfileType.Audiobook ? CoreQuality.M4B.Id : CoreQuality.EPUB.Id;
                profile.ConvertMp3ToM4b = profile.ProfileType == ProfileType.Audiobook;
                profile.MergeMultiPartFiles = profile.ProfileType == ProfileType.Audiobook;
                profile.PreferCustomFormatsOverQuality = profile.ProfileType == ProfileType.Audiobook;
                var specificId = _formats[profile.ProfileType == ProfileType.Audiobook ? 1 : 2].Id;
                Assert.That(profile.FormatItems.Single(item => item.Format.Id == specificId).Score, Is.Zero);
                profile.FormatItems.Single(item => item.Format.Id == specificId).Score = 91;
                _repository.Update(profile);
            }

            source.Name = "Renamed";
            source.FormatItems[0].Score = 37;
            _subject.Update(created.LegacyId, source);
            foreach (var profile in _repository.Get(ids))
            {
                Assert.That(profile.Name, Is.EqualTo("Renamed"));
                Assert.That(profile.ConvertToQualityId, Is.EqualTo(profile.ProfileType == ProfileType.Audiobook ? CoreQuality.M4B.Id : CoreQuality.EPUB.Id));
                Assert.That(profile.MergeMultiPartFiles, Is.EqualTo(profile.ProfileType == ProfileType.Audiobook));
                Assert.That(profile.PreferCustomFormatsOverQuality, Is.EqualTo(profile.ProfileType == ProfileType.Audiobook));
                Assert.That(profile.FormatItems.Select(item => item.Score), Is.EqualTo(new[] { 37, 91 }));
            }
        }

        [TestCase("create")]
        [TestCase("update")]
        [TestCase("delete")]
        public void failure_on_second_counterpart_rolls_back_profiles_mapping_counter_and_sequences(string operation)
        {
            var created = _subject.Create(Generic("Before"));
            var before = Snapshot();
            var sqlOperation = operation == "create" ? "INSERT" : operation == "update" ? "UPDATE" : "DELETE";
            var row = operation == "create" ? "NEW" : "OLD";
            using (var connection = Open())
            {
                if (Backend == DatabaseType.PostgreSQL)
                {
                    connection.Execute($@"CREATE FUNCTION fail_profile_ebook() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN IF {row}.""ProfileType""=2 THEN RAISE EXCEPTION 'injected second-counterpart failure'; END IF; RETURN {row}; END; $$;
CREATE TRIGGER fail_ebook BEFORE {sqlOperation} ON ""QualityProfiles"" FOR EACH ROW EXECUTE FUNCTION fail_profile_ebook();");
                }
                else
                {
                    connection.Execute($"CREATE TRIGGER fail_ebook BEFORE {sqlOperation} ON QualityProfiles WHEN {row}.ProfileType=2 BEGIN SELECT RAISE(ABORT,'injected second-counterpart failure'); END");
                }
            }

            Assert.Catch<System.Data.Common.DbException>(() =>
            {
                if (operation == "create")
                {
                    _subject.Create(Generic("Rejected"));
                }
                else if (operation == "update")
                {
                    _subject.Update(created.LegacyId, Generic("Rejected"));
                }
                else
                {
                    _subject.Delete(created.LegacyId);
                }
            });
            Assert.That(Snapshot(), Is.EqualTo(before));
        }

        [TestCase("author")]
        [TestCase("list")]
        [TestCase("root")]
        public void either_counterpart_in_use_blocks_the_whole_delete(string reference)
        {
            var created = _subject.Create(Generic("In use"));
            var ebookId = NativeIds(created.LegacyId).Last();
            if (reference == "author")
            {
                _authors.Add(new Author { EbookQualityProfileId = ebookId });
            }
            else if (reference == "list")
            {
                _lists.Add(new ImportListDefinition { QualityProfileId = ebookId });
            }
            else
            {
                var root = new RootFolder();
                root.SetEbookSettings(new MediaTypeSettings { QualityProfileId = ebookId });
                _roots.Add(root);
            }

            var before = Snapshot();
            Assert.Throws<QualityProfileInUseException>(() => _subject.Delete(created.LegacyId));
            Assert.That(Snapshot(), Is.EqualTo(before));
        }

        [Test]
        public void unmapped_native_audio_can_acquire_a_counterpart_without_colliding_with_exposed_ids()
        {
            _subject.Create(Generic("Imported"));
            var native = Generic("Native audio");
            native.ProfileType = ProfileType.Audiobook;
            _repository.Insert(native);
            Assert.That(native.Id, Is.EqualTo(3));
            var created = _subject.Create(Generic("Legacy new"));
            Assert.That(created.LegacyId, Is.EqualTo(4));
            _subject.Update(3, Generic("Native now generic"));
            Assert.That(NativeIds(3).Count, Is.EqualTo(2));
            Assert.That(_subject.Get(3).Profile.Id, Is.EqualTo(native.Id));
            Assert.That(_subject.All().Select(profile => profile.LegacyId), Is.EquivalentTo(new[] { 1, 3, 4 }));
        }

        [Test]
        public void concurrent_creates_keep_unique_stable_legacy_ids()
        {
            var tasks = Enumerable.Range(0, 12).Select(index => Task.Run(() => _subject.Create(Generic("Concurrent " + index)))).ToArray();
            Task.WaitAll(tasks);
            Assert.That(tasks.Select(task => task.Result.LegacyId).Distinct().Count(), Is.EqualTo(12));
            Assert.That(_repository.Count(), Is.EqualTo(24));
            Assert.That(NewService().All().Select(profile => profile.LegacyId).OrderBy(id => id), Is.EqualTo(Enumerable.Range(1, 12)));
        }

